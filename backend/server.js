// --------------------
// CREATE PHARMACY ORDER
// --------------------
app.post("/api/pharmacy/orders", (req, res) => {
  const {
    patientName,
    phone,
    address,
    paymentMethod,
    items
  } = req.body;

  if (!patientName || !phone || !address) {
    return res.status(400).json({
      success: false,
      message: "Patient name, phone and address are required"
    });
  }

  if (!Array.isArray(items) || items.length === 0) {
    return res.status(400).json({
      success: false,
      message: "At least one medicine is required"
    });
  }

  // Validate medicines and calculate total
  let total = 0;

  for (const item of items) {
    const medicine = medicines.find(
      m => m.id === item.id
    );

    if (!medicine) {
      return res.status(400).json({
        success: false,
        message: `Medicine ${item.id} not found`
      });
    }

    const quantity = Number(item.quantity);

    if (!Number.isInteger(quantity) || quantity < 1) {
      return res.status(400).json({
        success: false,
        message: "Invalid medicine quantity"
      });
    }

    if (medicine.stock < quantity) {
      return res.status(400).json({
        success: false,
        message: `${medicine.name} is out of stock`
      });
    }

    total += medicine.price * quantity;
  }

  // Reduce stock
  for (const item of items) {
    const medicine = medicines.find(
      m => m.id === item.id
    );

    medicine.stock -= Number(item.quantity);
  }

  const order = {
    id: `ORD-${Date.now()}`,
    patientName: String(patientName).trim(),
    phone: String(phone).trim(),
    address: String(address).trim(),
    paymentMethod: paymentMethod || "Cash",
    items,
    total,
    status: "pending",
    createdAt: new Date().toISOString()
  };

  pharmacyOrders.push(order);

  res.status(201).json({
    success: true,
    message: "Pharmacy order created successfully",
    order
  });
});

