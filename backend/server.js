// ====================
// WEBSOCKET SERVER
// ====================

const wss = new WebSocket.Server({
  server,
  path: "/ws/messaging"
});

const clients = new Map();

wss.on("connection", (ws) => {
  console.log("WebSocket client connected");

  let clientId = null;

  ws.on("message", (message) => {
    try {
      const data = JSON.parse(message.toString());

      // Register encryption key
      if (data.type === "register_key") {
        clientId = data.userId || `client-${Date.now()}`;

        clients.set(clientId, {
          ws,
          publicKeyJwk: data.publicKeyJwk
        });

        ws.send(
          JSON.stringify({
            type: "registered",
            userId: clientId
          })
        );

        console.log("Client registered:", clientId);
      }

      // Request doctor list
      else if (data.type === "request_doctor_list") {
        const doctors = [];

        for (const [id, client] of clients.entries()) {
          if (id.startsWith("doctor")) {
            doctors.push({
              id,
              name: "Demo Doctor",
              available: true,
              publicKeyJwk: client.publicKeyJwk
            });
          }
        }

        ws.send(
          JSON.stringify({
            type: "doctor_list",
            doctors
          })
        );
      }

      // Send encrypted message
      else if (data.type === "send_message") {
        const recipient = clients.get(data.to);

        if (!recipient) {
          ws.send(
            JSON.stringify({
              type: "error",
              error: "Doctor is not currently connected."
            })
          );
          return;
        }

        recipient.ws.send(
          JSON.stringify({
            type: "message",
            from: clientId,
            senderPublicKeyJwk:
              clients.get(clientId)?.publicKeyJwk,
            ciphertext: data.ciphertext,
            iv: data.iv,
            senderName: "MediKiosk User"
          })
        );
      }

      // Doctor availability
      else if (data.type === "set_availability") {
        console.log(
          `Client ${clientId} availability:`,
          data.available
        );
      }
    } catch (error) {
      console.error("WebSocket message error:", error);

      ws.send(
        JSON.stringify({
          type: "error",
          error: "Invalid WebSocket message."
        })
      );
    }
  });

  ws.on("close", () => {
    if (clientId) {
      clients.delete(clientId);
      console.log("Client disconnected:", clientId);
    }
  });
});

